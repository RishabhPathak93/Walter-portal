import Link from "next/link";
import { Alert, Card, CardHeader, LinkButton, PageHeader, StatCard, buttonClass, tableClass, tdClass, thClass } from "@/components/ui";
import { CompetitionStatusBadge } from "@/components/competition-status";
import { LocalTime } from "@/components/local-time";
import { LeaderboardTable } from "@/components/leaderboard-table";
import { requireAdminPage } from "@/lib/admin-page";
import { adminLeaderboard, getAdminOverview } from "@/lib/services/admin";
import { getCompetition } from "@/lib/services/queries";

export default async function AdminOverviewPage() {
  const viewer = await requireAdminPage();
  const [overview, competition, leaderboard] = await Promise.all([
    getAdminOverview(),
    getCompetition(),
    adminLeaderboard(viewer.user.id),
  ]);

  return (
    <>
      <PageHeader
        title="Overview"
        description="Competition health at a glance."
        actions={
          <>
            <CompetitionStatusBadge state={competition.state} />
            {/* Plain link: the CSV is generated by an admin-only API route. */}
            <a href="/api/admin/leaderboard?format=csv" className={buttonClass("secondary", "sm")} download>
              Export leaderboard CSV
            </a>
          </>
        }
      />
      {overview.challenges > 0 && overview.activeChallenges === 0 ? (
        <Alert tone="warn" className="mb-6" title="No active challenges">
          Participants cannot see any challenges.{" "}
          <Link href="/admin/challenges" className="text-accent underline">
            Activate challenges
          </Link>
          .
        </Alert>
      ) : null}

      <section className="grid gap-4 sm:grid-cols-2 lg:grid-cols-5">
        <StatCard label="Accounts" value={overview.participants} hint="incl. administrators" />
        <StatCard label="Challenges" value={`${overview.activeChallenges}/${overview.challenges}`} hint="active / total" />
        <StatCard label="Accepted solves" value={overview.acceptedSolves} />
        <StatCard label="Attempts" value={overview.totalAttempts} />
        <StatCard
          label="Incorrect"
          value={overview.incorrectAttempts}
          hint={overview.totalAttempts ? `${Math.round((overview.incorrectAttempts / overview.totalAttempts) * 100)}% of attempts` : undefined}
        />
      </section>

      <div className="mt-6 grid gap-6 lg:grid-cols-2">
        <Card>
          <CardHeader
            title="Current rankings"
            action={
              <LinkButton href="/leaderboard" size="sm" variant="secondary">
                Public board
              </LinkButton>
            }
          />
          {leaderboard.length ? (
            <LeaderboardTable entries={leaderboard.slice(0, 10)} compact />
          ) : (
            <p className="px-5 py-6 text-sm text-muted">No participants yet.</p>
          )}
        </Card>
        <Card>
          <CardHeader
            title="Latest accepted solves"
            action={
              <LinkButton href="/admin/submissions?view=solves" size="sm" variant="secondary">
                All solves
              </LinkButton>
            }
          />
          {overview.recentSolves.length === 0 ? (
            <p className="px-5 py-6 text-sm text-muted">No solves yet.</p>
          ) : (
            <div className="overflow-x-auto">
              <table className={tableClass}>
                <thead className="border-b border-line">
                  <tr>
                    <th scope="col" className={thClass}>Participant</th>
                    <th scope="col" className={thClass}>Challenge</th>
                    <th scope="col" className={`${thClass} text-right`}>Pos</th>
                    <th scope="col" className={`${thClass} text-right`}>Pts</th>
                    <th scope="col" className={`${thClass} text-right`}>Time</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-line">
                  {overview.recentSolves.map((s) => (
                    <tr key={s.id}>
                      <td className={`${tdClass} font-mono`}>{s.username}</td>
                      <td className={tdClass}>{s.challengeTitle}</td>
                      <td className={`${tdClass} text-right font-mono`}>#{s.position}</td>
                      <td className={`${tdClass} text-right font-mono text-accent`}>{s.points}</td>
                      <td className={`${tdClass} text-right text-muted`}>
                        <LocalTime iso={s.solvedAt} mode="time" />
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </Card>
      </div>
    </>
  );
}
